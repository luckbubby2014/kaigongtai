/**
 * 家常菜谱库
 * main：主料，每一项是一个「需求」。字符串为食材 key，数组表示任选其一，'cat:veg' 表示任意该品类食材。
 * opt：可选配料，有就更好，用到会加分。
 * cond：常备调料，仅展示，不计入缺料。
 */

export type Allergen = 'egg' | 'milk' | 'seafood' | 'peanut' | 'soy' | 'wheat' | 'sesame' | 'nut';

export const ALLERGENS: Record<Allergen, string> = {
  egg: '蛋类',
  milk: '乳制品',
  seafood: '鱼虾贝类',
  peanut: '花生',
  soy: '大豆',
  wheat: '小麦（麸质）',
  sesame: '芝麻',
  nut: '坚果',
};

export type Need = string | string[];

export interface Recipe {
  id: string;
  name: string;
  emoji: string;
  /** 分钟 */
  time: number;
  /** 难度 1–3 */
  level: 1 | 2 | 3;
  main: Need[];
  opt: string[];
  cond: string[];
  steps: string[];
  tags: string[];
  allergens: Allergen[];
  /** 是否含荤 */
  meat?: boolean;
  /** 涉及明火 / 热油 / 刀具较多 */
  fire?: boolean;
  /** 含酒精 */
  alcohol?: boolean;
}

const GREENS = ['spinach', 'bokchoy', 'lettuce', 'napa', 'cabbage'];
const PORKS = ['pork', 'porkbelly', 'mince'];
const NOODLES = ['noodle', 'drynoodle'];

function r(
  id: string, name: string, emoji: string, time: number, level: 1 | 2 | 3,
  main: Need[], opt: string[], cond: string, steps: string[],
  tags: string, allergens: Allergen[] = [], flags: Partial<Pick<Recipe, 'meat' | 'fire' | 'alcohol'>> = {},
): Recipe {
  return {
    id, name, emoji, time, level, main, opt, steps, allergens,
    cond: cond ? cond.split('、') : [],
    tags: tags ? tags.split('、') : [],
    fire: true,
    ...flags,
  };
}

